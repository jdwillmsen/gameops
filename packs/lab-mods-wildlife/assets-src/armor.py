"""Animal armor: the tiers, the barding geometry and its textures.

Tier numbers are the values of the entity property gameops:armor; 0 is no armor.
"""
import json
from dataclasses import dataclass

import build_models
import build_textures
import rig_common
from species import Species

ARMOR_PROPERTY = "gameops:armor"
# Only these cubes carry barding, so the head, legs and tail keep the animal readable.
COVERED = ("chest", "rear")
INFLATE = 0.6


@dataclass(frozen=True)
class Tier:
    number: int
    name: str
    item: str
    # Damage taken is multiplied by this.
    multiplier: float
    sound: str
    plate: tuple
    edge: tuple
    rivet: tuple


TIERS = (
    Tier(1, "leather", "minecraft:leather_horse_armor", 0.8, "armor.equip_leather",
         (140, 92, 54), (92, 58, 32), (196, 156, 112)),
    Tier(2, "iron", "minecraft:iron_horse_armor", 0.6, "armor.equip_iron",
         (178, 182, 188), (110, 114, 122), (232, 234, 238)),
    Tier(3, "diamond", "minecraft:diamond_horse_armor", 0.4, "armor.equip_diamond",
         (74, 214, 206), (30, 128, 134), (196, 252, 246)),
)


def group_name(n: int) -> str:
    return f"gameops:armor_{n}"


def event_name(n: int) -> str:
    return f"gameops:armor_{n}"


def texture_path(s: Species, t: Tier) -> str:
    return f"textures/entity/{s.id}_armor_{t.name}"


def geometry_id(s: Species) -> str:
    return f"geometry.gameops.{s.id}_armor"


def covered_parts(s: Species) -> list:
    return [p for p in build_models.rig_layout(s) if p.name in COVERED]


def geometry(s: Species) -> dict:
    """The base rig with only the covered cubes kept, each swollen so the plates sit over the coat.

    Every bone stays, so the shared animations move the barding with the body.
    """
    doc = build_models.geometry(s)
    keep = {(tuple(p.origin), tuple(p.size), tuple(p.uv)) for p in covered_parts(s)}
    geo = doc["minecraft:geometry"][0]
    geo["description"]["identifier"] = geometry_id(s)
    for bone in geo["bones"]:
        bone["cubes"] = [dict(c, inflate=INFLATE) for c in bone["cubes"]
                         if (tuple(c["origin"]), tuple(c["size"]), tuple(c["uv"])) in keep]
    return doc


def pixel(face: str, col: int, row: int, cols: int, rows: int, t: Tier) -> tuple:
    """Plate with a darker rim, a centre seam and rivets at the corners; None for the underside."""
    if face == "bottom":
        return None
    if col in (0, cols - 1) or row in (0, rows - 1):
        return t.rivet if col in (0, cols - 1) and row in (0, rows - 1) else t.edge
    if face in ("front", "back", "left", "right") and rows > 3 and row == rows // 2:
        return t.edge
    return t.plate


def paint(s: Species, t: Tier) -> bytes:
    size = rig_common.TEXTURE
    pixels = bytearray(size * size * 4)
    for part in covered_parts(s):
        for face, fx, fy, cols, rows, _ in build_textures.faces(part):
            for row in range(rows):
                for col in range(cols):
                    rgb = pixel(face, col, row, cols, rows, t)
                    if rgb is None:
                        continue
                    i = ((fy + row) * size + fx + col) * 4
                    pixels[i:i + 4] = bytes((*rgb, 255))
    return build_textures.png(pixels)


def loot_table(base: dict, t: Tier) -> dict:
    """The species' normal drops plus the armor that was worn, returned whole."""
    pool = {"rolls": 1, "entries": [{"type": "item", "name": t.item, "weight": 1}]}
    return {"pools": base["pools"] + [pool]}


def script_module() -> bytes:
    """Tier table for main.js, so the script and the entity files cannot disagree."""
    tiers = {t.item: {"tier": t.number, "name": t.name, "sound": t.sound} for t in TIERS}
    return ("// Generated by assets-src/generate.py; do not edit.\n"
            f"export const ARMOR_PROPERTY = {json.dumps(ARMOR_PROPERTY)};\n"
            f"export const ARMOR_ITEMS = {json.dumps(tiers, indent=2)};\n").encode()
